test('infraestrutura, eventos, políticas, evolução e ônibus persistem no mundo jogável', async ({ page }, info) => {
  test.setTimeout(150_000);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await start(page);
  const original = { ...fullyServedCity(), day: 59, event: { id: 59, kind: 'investment' as const } };
  await page.getByRole('button', { name: 'Salvamentos', exact: true }).click();
  await page.getByLabel('Arquivo JSON da cidade').setInputFiles({ name: 'cidade.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) });
  await expect(page.getByRole('status')).toContainText('Cidade importada');
  await page.getByRole('button', { name: 'Eventos', exact: true }).click();
  await page.getByRole('button', { name: /Exigir contrapartida/ }).click();
  await expect(page.locator('.event-history')).toContainText('Exigir contrapartida');
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByRole('button', { name: 'Energia e água', exact: true }).click();
  const power = page.locator('.facility-card').filter({ hasText: 'Subestação elétrica' });
  await power.getByRole('slider').fill('150');
  await power.getByRole('button', { name: /^Construir/ }).click();
  await cellClick(page, 21, 21);
  await page.keyboard.press('v'); await cellClick(page, 21, 21);
  await expect(page.locator('.selection-card')).toContainText('Subestação elétrica');
  await page.getByRole('button', { name: 'Políticas', exact: true }).click();
  await page.getByRole('checkbox', { name: /Coleta seletiva/ }).check();
  await page.getByRole('dialog').getByRole('button', { name: 'Mapas', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: /Energia.*Atendimento/ }).click();
  await page.getByRole('button', { name: 'Ver a camada no mapa' }).click();
  await expect(page.locator('.layer-legend')).toContainText('Energia');
  await page.getByRole('button', { name: 'Desativar camada' }).click();
  await page.getByRole('button', { name: 'Transporte', exact: true }).click();
  await page.locator('.facility-card').filter({ hasText: 'Estação de ônibus' }).getByRole('button', { name: /^Construir/ }).click();
  await cellClick(page, 29, 21); await cellClick(page, 32, 21);
  await page.getByRole('button', { name: 'Transporte', exact: true }).click();
  await page.getByLabel('Estação de origem').selectOption('29,21');
  await page.getByLabel('Estação de destino').selectOption('32,21');
  await page.getByRole('button', { name: 'Criar linha', exact: true }).click();
  await expect(page.locator('.bus-lines')).toContainText('Linha 1');
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.getByRole('button', { name: 'Velocidade 4x' }).click();
  await page.waitForTimeout(9000);
  await page.getByRole('button', { name: 'Pausar simulação', exact: true }).click();
  await page.keyboard.press('v'); await cellClick(page, 23, 19);
  await expect(page.locator('.selection-card')).toContainText('Nível');
  await expect(page.locator('.selection-card')).toContainText('2 / 3');
  await page.screenshot({ path: info.outputPath('cidade-integrada.png') });
  await page.getByRole('button', { name: 'Transporte', exact: true }).click();
  const agents = page.locator('.transport-summary > div').filter({ hasText: 'AGENTES ATIVOS' }).locator('strong');
  expect(Number(await agents.innerText())).toBeGreaterThan(0);
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.keyboard.press('Control+s');
  await expect(page.getByRole('status')).toContainText('Cidade salva');
  const city = await readSlot(page);
  expect(city.version).toBe(2); expect(city.funding.power).toBe(150); expect(city.policies.recycling).toBe(true);
  expect(city.facilities['21,21'].kind).toBe('power'); expect(city.busLines).toHaveLength(1);
  expect(city.eventHistory[0].choice).toBe(1); expect(city.lots['23,19'].building!.level).toBe(2);
  expect(getMetrics(city).coverage.energy).toBe(1); expect(getMetrics(city).utilities.waste.demand).toBeLessThan(getMetrics({ ...city, policies: { ...city.policies, recycling: false } }).utilities.waste.demand);
  expect(errors).toEqual([]);
});

test('save da versão publicada anterior é importado e migrado sem perder a cidade', async ({ page }) => {
  await start(page);
  const base = createCity('Cidade clássica');
  const legacy = { version: 1, id: base.id, name: base.name, seed: base.seed, roads: { '20,20': { x: 20, z: 20, kind: 'street' } }, lots: { '20,19': { x: 20, z: 19, kind: 'residential', building: { variant: 0, age: 15, occupants: 6 } } }, treasury: 1_234_567, day: 18, taxRate: 9, history: [], totalConstruction: 1200 };
  await page.getByRole('button', { name: 'Salvamentos', exact: true }).click();
  await page.getByLabel('Arquivo JSON da cidade').setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(legacy)) });
  await expect(page.locator('.city-identity')).toContainText('Cidade clássica');
  await expect(page.getByTestId('population')).toHaveText('6');
  await page.keyboard.press('Control+s'); await expect(page.getByRole('status')).toContainText('Cidade salva');
  const restored = await readSlot(page);
  expect(restored.version).toBe(2); expect(restored.treasury).toBe(legacy.treasury); expect(restored.day).toBe(18);
  expect(restored.facilities).toEqual({}); expect(restored.lots['20,19'].building!.occupants).toBe(6);
});

test('câmera se move, aproxima e gira durante a pausa com renderização sob demanda', async ({ page }) => {
  await start(page);
  await page.keyboard.press('v'); await page.waitForTimeout(700);
  const before = await page.screenshot();
  await page.keyboard.down('w'); await page.waitForTimeout(400); await page.keyboard.up('w'); await page.waitForTimeout(500);
  const moved = await page.screenshot(); expect(before.equals(moved)).toBe(false);
  await page.mouse.move(900, 400); await page.mouse.wheel(0, -700); await page.waitForTimeout(700);
  const zoomed = await page.screenshot(); expect(moved.equals(zoomed)).toBe(false);
  await page.mouse.down({ button: 'right' }); await page.mouse.move(1040, 450, { steps: 12 }); await page.mouse.up({ button: 'right' }); await page.waitForTimeout(700);
  const rotated = await page.screenshot(); expect(zoomed.equals(rotated)).toBe(false);
  await page.keyboard.press('f'); await page.waitForTimeout(1000);
  await page.keyboard.press('1'); await cellClick(page, 20, 20); await cellClick(page, 24, 20);
  await page.keyboard.press('Control+s'); await expect(page.getByRole('status')).toContainText('Cidade salva');
  expect(Object.keys((await readSlot(page)).roads)).toHaveLength(5);
});
